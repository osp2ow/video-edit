import { chromium } from 'playwright-core';
const NM = '/home/claude/pve/node_modules';
const map = { 'react.production.min.js': NM + '/react/umd/react.production.min.js', 'react-dom.production.min.js': NM + '/react-dom/umd/react-dom.production.min.js', 'pdf.min.js': NM + '/pdfjs-dist/build/pdf.min.js', 'pdf.worker.min.js': NM + '/pdfjs-dist/build/pdf.worker.min.js' };
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell' });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
const logs = []; page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message));
await page.route('**/*', r => { const u = r.request().url(); const f = Object.keys(map).find(k => u.endsWith('/' + k)); if (f) return r.fulfill({ path: map[f], contentType: 'application/javascript' }); if (u.includes('fonts.g')) return r.abort(); return r.continue(); });
await page.goto('file:///home/claude/pve/dist/index.html');
await page.setInputFiles('#f-sheet', '/home/claude/poc/in/sheet.pdf');
await page.setInputFiles('#f-video', 'test/test.webm');
await page.setInputFiles('#f-rec', '/home/claude/poc/in/rec.mp3');
await page.waitForFunction(() => document.querySelector('.status')?.textContent?.includes('자동 감지'), null, { timeout: 60000 });
await page.waitForTimeout(500);
const state = () => page.evaluate(() => { const p = JSON.parse(localStorage.getItem('pve.proj:test.webm')); const l = JSON.parse(localStorage.getItem('pve.layouts'))['9:16']; return `offset=${p.sheetOffset} bpm=${p.bpm} cardY=${l.y.toFixed(3)}`; });
console.log('start  ', await state());
await page.click('text=+1마디'); await page.waitForTimeout(700);
console.log('+1마디 ', await state());
const box = await page.locator('canvas.stage').boundingBox();
await page.mouse.move(box.x + box.width / 2, box.y + box.height * 0.2); await page.mouse.down();
for (let i = 1; i <= 10; i++) await page.mouse.move(box.x + box.width / 2, box.y + box.height * (0.2 + i * 0.02));
await page.mouse.up(); await page.waitForTimeout(700);
console.log('drag   ', await state());
await page.fill('#bpm', '95'); await page.keyboard.press('Enter'); await page.waitForTimeout(700);
console.log('bpm95  ', await state());
await page.keyboard.press('Control+z'); await page.waitForTimeout(300); console.log('undo1  ', await state());
await page.keyboard.press('Control+z'); await page.waitForTimeout(300); console.log('undo2  ', await state());
await page.keyboard.press('Control+z'); await page.waitForTimeout(300); console.log('undo3  ', await state());
await page.keyboard.press('Control+Shift+z'); await page.waitForTimeout(300); console.log('redo   ', await state());
console.log(logs.join('\n'));
await browser.close();
